#!/usr/bin/env bash
# =============================================================================
#  runlog.sh — 명령어 입력과 출력 결과를 "짝"으로 로그 파일에 남기는 헬퍼
# =============================================================================
#  왜 필요한가:
#    미션 제약사항(mission.txt L167)이 "캡처/로그에는 '명령어 입력'과
#    '출력 결과'가 함께 포함되어야 한다"고 요구한다.
#    사람이 손으로 복붙하면 명령어를 빠뜨리기 쉬우므로,
#    이 헬퍼로 실행하면 구조적으로 누락이 불가능해진다.
#
#  사용법:
#    export LOGFILE=logs/01-terminal.log
#    source scripts/runlog.sh
#    logrun pwd
#    logrun ls -la
#    logsh  'echo hi > a.txt && cat a.txt'   # 파이프/리다이렉션이 있는 명령
#
#  출력 형식 (로그 파일):
#    $ pwd
#    /Users/ellysuh/Documents/1-homework
# =============================================================================

: "${LOGFILE:?LOGFILE 환경변수로 로그 파일 경로를 지정하세요}"
mkdir -p "$(dirname "$LOGFILE")"

# LOGFILE 을 반드시 절대 경로로 바꾼다.
#   실습 도중 cd 로 작업 위치가 바뀌면 "logs/01-terminal.log" 같은 상대 경로는
#   더 이상 유효하지 않아 로그가 통째로 유실된다. (실제로 겪은 문제 — README 16장 참고)
LOGFILE="$(cd "$(dirname "$LOGFILE")" && pwd)/$(basename "$LOGFILE")"

# 로그 파일 헤더 (수집 시각 기록 → 재현성 근거)
{
  printf '===============================================================\n'
  printf ' %s\n' "$(basename "$LOGFILE")"
  printf ' 수집 시각: %s\n' "$(date '+%Y-%m-%d %H:%M:%S %Z')"
  printf ' 수집 방법: scripts/runlog.sh (명령어+출력 동시 기록)\n'
  printf '===============================================================\n'
} >> "$LOGFILE"

# ---------------------------------------------------------------------------
# _fmt_cmd: 명령어를 "복붙하면 그대로 실행되는" 형태로 되살린다.
#   "$*" 를 그대로 쓰면 공백이 든 인자의 따옴표가 사라져서
#   로그를 보고 따라 쳤을 때 다른 명령이 되어버린다. (재현성 훼손)
# ---------------------------------------------------------------------------
_fmt_cmd() {
  local out="" a
  for a in "$@"; do
    case "$a" in
      "" ) out="$out ''" ;;
      *[![:alnum:]_/.:=@%+-]* ) out="$out '${a//\'/\'\\\'\'}'" ;;
      * ) out="$out $a" ;;
    esac
  done
  printf '%s' "${out# }"
}

# ---------------------------------------------------------------------------
# logrun: 일반 명령 실행. 명령어 한 줄 + 출력 + (실패 시) 종료 코드를 기록한다.
# ---------------------------------------------------------------------------
logrun() {
  local out rc cmd
  cmd="$(_fmt_cmd "$@")"
  out=$("$@" 2>&1); rc=$?
  {
    printf '\n$ %s\n' "$cmd"
    printf '%s\n' "$out"
    [ "$rc" -ne 0 ] && printf '[exit code: %s]\n' "$rc"
  } >> "$LOGFILE"
  printf '\n$ %s\n%s\n' "$cmd" "$out"
  [ "$rc" -ne 0 ] && printf '[exit code: %s]\n' "$rc"
  return 0   # 실패해도 스크립트를 멈추지 않는다 (에러 재현 실습을 위해)
}

# ---------------------------------------------------------------------------
# logsh: 파이프(|), 리다이렉션(>), &&  등 셸 문법이 포함된 명령용
# ---------------------------------------------------------------------------
logsh() {
  local out rc
  out=$(bash -c "$*" 2>&1); rc=$?
  {
    printf '\n$ %s\n' "$*"
    printf '%s\n' "$out"
    [ "$rc" -ne 0 ] && printf '[exit code: %s]\n' "$rc"
  } >> "$LOGFILE"
  printf '\n$ %s\n%s\n' "$*" "$out"
  [ "$rc" -ne 0 ] && printf '[exit code: %s]\n' "$rc"
  return 0
}

# ---------------------------------------------------------------------------
# logcd: 디렉토리 이동 전용
#   logrun 은 명령을 서브셸에서 실행하므로 cd 가 현재 셸에 반영되지 않는다.
#   그래서 cd 만 따로 처리한다. (이동 결과는 이어서 logrun pwd 로 확인)
# ---------------------------------------------------------------------------
logcd() {
  { printf '\n$ cd %s\n' "$1"; } >> "$LOGFILE"
  printf '\n$ cd %s\n' "$1"
  cd "$1" || return 1
}

# ---------------------------------------------------------------------------
# lognote: 로그 파일에 설명 주석을 남긴다 (실습 구간 구분용)
# ---------------------------------------------------------------------------
lognote() {
  { printf '\n### %s\n' "$*"; } >> "$LOGFILE"
  printf '\n### %s\n' "$*"
}
